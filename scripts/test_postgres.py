#!/usr/bin/env python3
"""Integration tests in a disposable, Unix-socket-only PostgreSQL 18 cluster."""
import argparse
from datetime import datetime, timezone
import getpass
from pathlib import Path
import shutil
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pg-config', default='pg_config')
    parser.add_argument('--backend', choices=('cpu', 'cuda'), default='cpu')
    parser.add_argument('--benchmark-smoke', action='store_true')
    parser.add_argument('--results-dir', type=Path, help='preserve logs/reports outside the disposable cluster')
    args = parser.parse_args()
    bindir = Path(subprocess.check_output([args.pg_config, '--bindir'], text=True).strip())
    root = Path(__file__).resolve().parents[1]
    work = Path(tempfile.mkdtemp(prefix='pg-gftr-test-', dir='/tmp'))
    started = False
    passed = False
    try:
        subprocess.run([str(bindir / 'initdb'), '-D', str(work / 'data'),
                        '-A', 'trust', '--no-locale', '-E', 'UTF8'],
                       check=True, stdout=subprocess.DEVNULL)
        # The path is generated by tempfile, never user-supplied shell input.
        subprocess.run([str(bindir / 'pg_ctl'), '-D', str(work / 'data'),
                        '-l', str(work / 'server.log'), '-w', '-o',
                        f"-F -k {work} -c listen_addresses=''", 'start'], check=True)
        started = True
        sql = (root / 'tests' / 'integration.sql').read_text()
        if args.backend == 'cuda':
            # Execute the complete correctness suite under both algorithms.
            sql = sql.replace('CREATE EXTENSION pg_gftr;',
                              "CREATE EXTENSION IF NOT EXISTS pg_gftr;")
        for mode in (('gftr', 'gfur') if args.backend == 'cuda' else ('gftr',)):
            # Each suite needs its own database and connection.
            db = f'gftr_test_{mode}'
            base = ['-h', str(work), '-U', getpass.getuser()]
            subprocess.run([str(bindir / 'createdb'), *base, db], check=True)
            cmd = [str(bindir / 'psql'), '-X', *base, '-d', db,
                   '-v', 'ON_ERROR_STOP=1', '-v', f'backend={args.backend}']
            with (work / f'{mode}.log').open('w') as log:
                script = f"SET pg_gftr.mode = '{mode}';\n" + sql
                subprocess.run(cmd, input=script, text=True, stdout=log,
                               stderr=subprocess.STDOUT, check=True)
            print(f'{args.backend}/{mode}: PostgreSQL integration tests passed')
        if args.benchmark_smoke:
            connection = f'host={work} user={getpass.getuser()} dbname=gftr_test_gftr'
            subprocess.run(['python3', str(root / 'bench' / 'benchmark.py'),
                            '--psql', str(bindir / 'psql'), '--dbname', connection,
                            '--backend', args.backend, '--rows', '20000', '--groups', '37',
                            '--columns', '2', '--trials', '2', '--output', str(work / 'bench')],
                           check=True)
            print('Benchmark harness smoke test passed')
        passed = True
    finally:
        if started:
            subprocess.run([str(bindir / 'pg_ctl'), '-D', str(work / 'data'),
                            '-m', 'immediate', '-w', 'stop'], check=False)
        if passed:
            if args.results_dir:
                stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
                saved = args.results_dir / f'{args.backend}-{stamp}'
                saved.mkdir(parents=True)
                for log in work.glob('*.log'):
                    shutil.copy2(log, saved / log.name)
                if (work / 'bench').exists():
                    shutil.copytree(work / 'bench', saved / 'bench')
                print(f'Verification logs and reports saved at {saved.resolve()}')
            shutil.rmtree(work)
        else:
            print(f'Test files and server log retained at {work}')


if __name__ == '__main__':
    main()
